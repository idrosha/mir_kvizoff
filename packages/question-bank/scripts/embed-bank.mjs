#!/usr/bin/env node
/**
 * Embeds content/question-bank/*.json into src/bank-data.ts for browser + Node builds.
 * Canonical content path: content/question-bank/
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../..");
const contentDir = path.join(repoRoot, "content/question-bank");
const outFile = path.resolve(here, "../src/bank-data.ts");

const files = fs
  .readdirSync(contentDir)
  .filter((name) => /^level-\d{2}-[a-z]+\.json$/.test(name))
  .sort();

if (files.length !== 10) {
  throw new Error(`Expected 10 level JSON files in ${contentDir}, found ${files.length}`);
}

const levels = files.map((name) => {
  const raw = fs.readFileSync(path.join(contentDir, name), "utf8");
  const parsed = JSON.parse(raw);
  if (!parsed.levelId || !Array.isArray(parsed.questions) || parsed.questions.length !== 30) {
    throw new Error(`Invalid bank file ${name}`);
  }
  return parsed;
});

levels.sort((a, b) => a.levelId - b.levelId);

const banner = `/* AUTO-GENERATED by scripts/embed-bank.mjs — do not edit.
 * Source: content/question-bank/
 */
import type { BankLevelFile } from "./bank-schema.js";

export const BANK_LEVEL_FILES: BankLevelFile[] = `;

const body = `${banner}${JSON.stringify(levels, null, 2)} as BankLevelFile[];
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, body, "utf8");
console.log(`Wrote ${outFile} (${levels.length} levels)`);
